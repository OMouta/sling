/**
 * Writes api-report.d.ts: the declarations of the SDK's public entry, plus
 * the @sling/workflow files it re-exports, as one file. Every change to the
 * SDK's API shows up as a change to this file.
 *
 *   pnpm --filter @sling/connector-sdk api-report
 */
import { spawnSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE = fileURLToPath(new URL("../", import.meta.url));
const PACKAGES = join(PACKAGE, "..");
const ROOT = join(PACKAGES, "..");
export const REPORT_PATH = join(PACKAGE, "api-report.d.ts");

/** Each source, in report order, with the name it's imported by. */
const SOURCES: [file: string, title: string][] = [
  ["connector-sdk/src/index.ts", "@sling/connector-sdk"],
  ["connector-sdk/src/connector.ts", "@sling/connector-sdk: connector.ts"],
  ["connector-sdk/src/extension.ts", "@sling/connector-sdk: extension.ts"],
  ["connector-sdk/src/manifest.ts", "@sling/connector-sdk: manifest.ts"],
  ["connector-sdk/src/node.ts", "@sling/connector-sdk: node.ts"],
  ["workflow/src/spec.ts", "@sling/workflow/spec, re-exported by node.ts"],
  ["workflow/src/types.ts", "@sling/workflow/types, re-exported by node.ts"],
];

const HEADER = `// biome-ignore-all lint: generated by tsc, with several files joined into one
// biome-ignore-all format: generated by tsc
// biome-ignore-all assist: generated by tsc
// The public API of @sling/connector-sdk: the declarations of its entry
// point and of the @sling/workflow files it re-exports. Generated, do not
// edit. A test fails when the SDK's exports change and this file doesn't.
// Regenerate it with: pnpm --filter @sling/connector-sdk api-report
`;

function tscPath(): string {
  const require = createRequire(join(PACKAGE, "package.json"));
  return join(dirname(require.resolve("typescript/package.json")), "bin", "tsc");
}

export async function generateApiReport(): Promise<string> {
  const out = await mkdtemp(join(tmpdir(), "sling-api-report-"));
  try {
    const tsconfig = {
      extends: join(ROOT, "tsconfig.base.json"),
      compilerOptions: {
        noEmit: false,
        declaration: true,
        emitDeclarationOnly: true,
        outDir: join(out, "d"),
        rootDir: PACKAGES,
        typeRoots: [join(ROOT, "node_modules/@types")],
      },
      files: SOURCES.map(([file]) => join(PACKAGES, file)),
    };
    const config = join(out, "tsconfig.json");
    await writeFile(config, JSON.stringify(tsconfig));
    const r = spawnSync(process.execPath, [tscPath(), "-p", config], { encoding: "utf8" });
    if (r.status !== 0) throw new Error(`tsc failed:\n${r.stdout}${r.stderr}`);
    const parts = [HEADER];
    for (const [file, title] of SOURCES) {
      const text = await readFile(join(out, "d", file.replace(/\.ts$/, ".d.ts")), "utf8");
      parts.push(
        `\n// ${"-".repeat(72)}\n// ${title}\n// ${"-".repeat(72)}\n\n${text.trimEnd()}\n`,
      );
    }
    return parts.join("");
  } finally {
    await rm(out, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  await writeFile(REPORT_PATH, await generateApiReport());
  console.log(`Wrote ${REPORT_PATH}`);
}
